async function fetchMetadata(url) {
    try {
        const res = await fetch(`https://open.spotify.com/oembed?url=${url}`);
        if (!res.ok) return null;
        const data = await res.json();
        let title = data.title || "Track";
        let artistName = "Spotify Artist";
        let coverUrl = data.thumbnail_url || "https://images.unsplash.com/photo-1511671782779-c97d3d27a1d4?w=400";
        
        if (title.includes(" by ")) {
            const parts = title.split(" by ");
            title = parts[0].trim();
            artistName = parts.slice(1).join(" by ").trim();
        } else if (title.includes(" - ")) {
            const parts = title.split(" - ");
            title = parts[0].trim();
            artistName = parts.slice(1).join(" - ").trim();
        }
        return { title, artistName, coverUrl };
    } catch (e) {
        return null;
    }
}

async function runFastImport() {
    console.log(`🚀 Starting fast parallel batch import for ${spotifyUrls.length} Spotify tracks...`);
    
    // Create Playlist
    const playlistId = await new Promise((res, rej) => {
        db.run(`INSERT INTO playlists (user_id, title, description, cover_color) VALUES (1, 'My Spotify Liked Songs', 'Imported 1000+ tracks directly from Spotify', '#1db954')`, function(err) {
            if (err) rej(err);
            else res(this.lastID);
        });
    });

    const BATCH_SIZE = 30;
    let totalImported = 0;

    for (let i = 0; i < spotifyUrls.length; i += BATCH_SIZE) {
        const batchUrls = spotifyUrls.slice(i, i + BATCH_SIZE);
        const results = await Promise.all(batchUrls.map(url => fetchMetadata(url)));

        await new Promise((resolve) => {
            db.serialize(() => {
                db.run("BEGIN TRANSACTION");
                results.forEach((item, batchIdx) => {
                    if (!item) return;
                    const pos = i + batchIdx + 1;
                    const { title, artistName, coverUrl } = item;
                    const albumName = `${artistName} Album`;
                    const duration = Math.floor(Math.random() * 60) + 180;
                    const bpm = Math.floor(Math.random() * 40) + 100;
                    const genreId = Math.floor(Math.random() * 7) + 1;

                    // Insert or ignore artist
                    db.run(`INSERT OR IGNORE INTO artists (artist_name, country, debut_year) VALUES (?, 'Global', 2022)`, [artistName], function() {
                        db.get(`SELECT artist_id FROM artists WHERE artist_name = ?`, [artistName], (err, artRow) => {
                            const artistId = artRow ? artRow.artist_id : 1;
                            
                            db.run(`INSERT OR IGNORE INTO albums (album_name, artist_id, release_year, cover_url) VALUES (?, ?, 2023, ?)`, [albumName, artistId, coverUrl], function() {
                                db.get(`SELECT album_id FROM albums WHERE album_name = ? AND artist_id = ?`, [albumName, artistId], (err, albRow) => {
                                    const albumId = albRow ? albRow.album_id : 1;

                                    db.run(`INSERT INTO songs (song_name, artist_id, album_id, genre_id, duration, bpm) VALUES (?, ?, ?, ?, ?, ?)`,
                                        [title, artistId, albumId, genreId, duration, bpm], function() {
                                        const songId = this.lastID;
                                        db.run(`INSERT INTO playlist_songs (playlist_id, song_id, position) VALUES (?, ?, ?)`, [playlistId, songId, pos]);
                                    });
                                });
                            });
                        });
                    });
                    totalImported++;
                });
                db.run("COMMIT", () => resolve());
            });
        });

        console.log(`⚡ Batch ${Math.floor(i / BATCH_SIZE) + 1}/${Math.ceil(spotifyUrls.length / BATCH_SIZE)} complete (${Math.min(i + BATCH_SIZE, spotifyUrls.length)}/${spotifyUrls.length} tracks processed)...`);
    }

    console.log(`\n🎉 ALL DONE! Imported ${totalImported} songs into playlist #${playlistId}!`);
    db.close();
}

runFastImport();
